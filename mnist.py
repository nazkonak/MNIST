#60.000 görüntüyü modele tek seferde veremeyiz, bellek patlar. DataLoader bunları küçük gruplar (batch) halinde veriyor.

from torch.utils.data import DataLoader

train_loader = DataLoader(train_data, batch_size=32, shuffle=True)#shuffle=True neden? Eğitimde karıştırıyoruz — model hep aynı sırada görürse ezberlemeye başlar.

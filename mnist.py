# PyTorch'un sinir ağı modülünü içe aktar
import torch.nn as nn

# nn.Module'den miras alan model sınıfı
class MNISTModel(nn.Module):

    def __init__(self):
        super().__init__()  # nn.Module'ü başlat

        # 1 kanallı görüntüyü al, 32 farklı özellik çıkar
        self.conv1 = nn.Conv2d(1, 32, kernel_size=3)

        # 32 özelliği al, 64 farklı özellik çıkar
        self.conv2 = nn.Conv2d(32, 64, kernel_size=3)

        # Görüntüyü yarıya küçült (28x28 → 14x14)
        self.pool  = nn.MaxPool2d(2)

        # Düzleştirilmiş veriyi 128 nörona bağla
        self.fc1 = nn.Linear(64 * 12 * 12, 128)

        # 128 nöronu 10 çıktıya bağla (0-9 rakamları)
        self.fc2   = nn.Linear(128, 10)

        # Negatif değerleri sıfırla
        self.relu  = nn.ReLU()

    # Görüntü modelden geçerken bu fonksiyon çalışır
    def forward(self, x):
        x = self.relu(self.conv1(x))      # conv1 → relu
        x = self.pool(self.relu(self.conv2(x)))  # conv2 → relu → pool
        x = x.view(x.size(0), -1)         # 3D → 1D düzleştir
        x = self.relu(self.fc1(x))         # fc1 → relu
        x = self.fc2(x)                    # fc2 → 10 çıktı
        return x

# Modeli GPU'ya taşı
model = MNISTModel().to('cuda')
print(model)

import torch.optim as optim

criterion = nn.CrossEntropyLoss()
optimizer = optim.Adam(model.parameters(), lr=0.001) #lr= learning rate

print('✅ Loss ve Optimizer hazır')

"""# **Loss (CrossEntropyLoss)**
**Modelin ne kadar yanıldığını ölçüyor.**

Gerçek: 5

Model tahmini: 3

Loss: yüksek → çok yanlış!

Gerçek: 5

Model tahmini: 5

Loss: düşük -> doğru!

# **Optimizer (Adam)**

**Loss'a bakarak modelin ağırlıklarını düzeltiyor.**

Loss yüksek -> "bir şeyler yanlış, düzelt!"

Loss düşük  -> "iyi gidiyoruz, devam!"

Şöyle düşün: Loss sınav notu, Optimizer ise notuna göre nasıl çalışacağını söyleyen hoca.
"""

DEVICE = 'cuda'
NUM_EPOCHS = 5

for epoch in range(1, NUM_EPOCHS + 1):
    model.train()
    total_loss, correct, total = 0, 0, 0

    for images, labels in train_loader:
        images, labels = images.to(DEVICE), labels.to(DEVICE)

        optimizer.zero_grad()
        outputs = model(images)
        loss = criterion(outputs, labels)
        loss.backward()
        optimizer.step()

        total_loss += loss.item()
        preds = outputs.argmax(dim=1)
        correct += (preds == labels).sum().item()
        total += labels.size(0)

    acc = correct / total
    print(f'Epoch [{epoch}/{NUM_EPOCHS}] Loss: {total_loss/len(train_loader):.4f} | Acc: {acc:.4f}')

model.eval()
correct, total = 0, 0

with torch.no_grad():
    for images, labels in test_loader:
        images, labels = images.to(DEVICE), labels.to(DEVICE)
        outputs = model(images)
        preds = outputs.argmax(dim=1)
        correct += (preds == labels).sum().item()
        total += labels.size(0)

print(f'Test Accuracy: {correct/total:.4f}')

